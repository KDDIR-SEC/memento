package main

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const (
	sosemanukLicenseSHA256 = "865ed187a779ce54342e881b5c97e62c6be0bb625e36d4da18af25e028e30dac"
	ubuntuRuntimeImage     = "ubuntu:24.04@sha256:f610ab94648195aa356059f5b41d6085c9d4d903c072430cdd1af7bdb646106b"
)

var forbiddenDependencies = []string{
	"github.com/spf13/cobra",
	"github.com/ecies/go",
	"github.com/ethereum/go-ethereum",
	"<openssl/",
	"-lcrypto",
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	if err := inspectRootLicense("LICENSE"); err != nil {
		return err
	}
	if err := inspectSosemanukLicense(
		"internal/crypto/sosemanuk/LICENSE",
		[]string{
			"internal/crypto/sosemanuk/sosemanuk.c",
			"internal/crypto/sosemanuk/sosemanuk.h",
		},
	); err != nil {
		return err
	}
	if err := inspectContainerBase("containers/lab/Dockerfile"); err != nil {
		return err
	}
	if err := inspectProjectLicensePolicy(); err != nil {
		return err
	}
	return inspectSources()
}

func inspectRootLicense(path string) error {
	data, err := readRequiredRegularFile(path)
	if err != nil {
		return err
	}
	for _, marker := range []string{"GNU GENERAL PUBLIC LICENSE", "Version 2, June 1991"} {
		if !bytes.Contains(data, []byte(marker)) {
			return fmt.Errorf("root license %q lacks required GPLv2 marker %q", path, marker)
		}
	}
	return nil
}

func inspectSosemanukLicense(licensePath string, sourcePaths []string) error {
	license, err := readRequiredRegularFile(licensePath)
	if err != nil {
		return err
	}
	digest := fmt.Sprintf("%x", sha256.Sum256(license))
	if digest != sosemanukLicenseSHA256 {
		return fmt.Errorf("Sosemanuk license %q has SHA-256 %s, want %s", licensePath, digest, sosemanukLicenseSHA256)
	}
	for _, path := range sourcePaths {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for _, marker := range []string{
			"SPDX-License-Identifier: LicenseRef-X-CRYPT-Sosemanuk",
			"(c) 2005 X-CRYPT project.",
			"Permission is granted to anyone to use this software for any purpose",
		} {
			if !bytes.Contains(data, []byte(marker)) {
				return fmt.Errorf("Sosemanuk source %q lacks required license marker %q", path, marker)
			}
		}
	}
	return nil
}

func inspectContainerBase(path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var fromLines []string
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "FROM ") {
			fromLines = append(fromLines, line)
		}
	}
	want := "FROM " + ubuntuRuntimeImage
	if len(fromLines) != 1 || fromLines[0] != want {
		return fmt.Errorf("container base must be pinned exactly as %q; found %q", want, fromLines)
	}
	return nil
}

func readRequiredRegularFile(path string) ([]byte, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, fmt.Errorf("required license file %q: %w", path, err)
	}
	if !info.Mode().IsRegular() || info.Size() == 0 {
		return nil, fmt.Errorf("required license file %q is empty or not regular", path)
	}
	return os.ReadFile(path)
}

func inspectProjectLicensePolicy() error {
	projectFiles := []string{
		"ebpf/getrandom.bpf.c",
		"ebpf/read.bpf.c",
		"evaluation/guest/src/guest_record.h",
		"evaluation/guest/src/rdrand_bench.c",
		"evaluation/tools/src/rndlog-verify.c",
	}
	for _, path := range projectFiles {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Contains(firstLines(data, 1), []byte("SPDX-License-Identifier: GPL-2.0-only")) {
			return fmt.Errorf("project source %s is not marked GPL-2.0-only", path)
		}
	}

	const bpfLicense = `char __license[] SEC("license") = "GPL";`
	for _, path := range []string{"ebpf/getrandom.bpf.c", "ebpf/read.bpf.c"} {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Contains(data, []byte(bpfLicense)) {
			return fmt.Errorf("eBPF source %s lacks the GPL kernel license declaration", path)
		}
	}
	return nil
}

func inspectSources() error {
	dualMITGPL := "Dual MIT" + "/GPL"
	return filepath.WalkDir(".", func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			if path == ".git" || path == "build" || path == "var" || path == "tools/licensecheck" {
				return filepath.SkipDir
			}
			return nil
		}
		extension := filepath.Ext(path)
		isMakefile := filepath.Base(path) == "Makefile"
		if extension != ".go" && extension != ".c" && extension != ".h" && extension != ".sh" && extension != ".py" && !isMakefile {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.Contains(data, []byte("Code generated by bpf2go")) || filepath.Base(path) == "vmlinux.h" {
			return nil
		}
		if bytes.Contains(data, []byte(dualMITGPL)) {
			return fmt.Errorf("source %s contains a dual-license declaration forbidden by the GPL-2.0-only project policy", path)
		}
		header := firstLines(data, 8)
		if !bytes.Contains(header, []byte("SPDX-License-Identifier:")) {
			return fmt.Errorf("source %s lacks an SPDX identifier", path)
		}
		wantLicense := "SPDX-License-Identifier: GPL-2.0-only"
		if path == "internal/crypto/sosemanuk/sosemanuk.c" || path == "internal/crypto/sosemanuk/sosemanuk.h" {
			wantLicense = "SPDX-License-Identifier: LicenseRef-X-CRYPT-Sosemanuk"
		}
		if !bytes.Contains(header, []byte(wantLicense)) {
			return fmt.Errorf("source %s does not use required license declaration %q", path, wantLicense)
		}
		if extension == ".go" || extension == ".c" || extension == ".h" {
			if marker := forbiddenDependencyMarker(data); marker != "" {
				return fmt.Errorf("forbidden dependency marker %q in %s", marker, path)
			}
		}
		return nil
	})
}

func forbiddenDependencyMarker(data []byte) string {
	for _, value := range forbiddenDependencies {
		if bytes.Contains(data, []byte(value)) {
			return value
		}
	}
	return ""
}

func firstLines(data []byte, count int) []byte {
	index := 0
	for offset, value := range data {
		if value == '\n' {
			index++
			if index == count {
				return data[:offset]
			}
		}
	}
	return data
}
